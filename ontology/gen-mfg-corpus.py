# 产物落在**本包内**的 ict-corpus-manufacturing/ —— 下游 §W2 读的就是这个相对路径。
# 不用绝对路径：包要分发给评委，`/home/<某人>/...` 在别人机器上会把产物写到包外，
# 于是「改了语料重跑 W1，W2 却读到旧文件」这种假绿就会出现。
OUT_DIR = os.environ.get("MFG_OUT_DIR") or os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ict-corpus-manufacturing"))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    out_path = os.path.join(OUT_DIR, "chunks.jsonl")
    n_doc = n_chunk = n_char = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for d in DOCS:
            doc_id = hashlib.sha1(d["title"].encode("utf-8")).hexdigest()[:16]
            n_doc += 1
            for i, para in enumerate(d["paras"]):
                rec = {
                    "chunk_id": "%s-%04d" % (doc_id, i),
                    "doc_id": doc_id,
                    "char_offset": 0,
                    "title": d["title"],
                    "date": d["date"],
                    "source": d["source"],
                    "text": para,
                }
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                n_chunk += 1
                n_char += len(para)
    print("文档 %d 篇 · 块 %d 个 · 正文 %d 字符 → %s" % (n_doc, n_chunk, n_char, out_path))


if __name__ == "__main__":
    main()
