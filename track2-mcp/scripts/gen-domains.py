DOMAINS = {
    "medical": MEDICAL,
    "software": SOFTWARE,
    "finance": FINANCE,
    "legal": LEGAL,
    "manufacturing": MANUFACTURING,
    "environment": ENVIRONMENT,
    "education": EDUCATION,
    "energy": ENERGY,
}
FIELDS = ("chunk_id", "doc_id", "char_offset", "title", "date", "source", "text")


def build_domain(rows: list, domain: str) -> list[dict]:
    """把 (标题, 来源, 日期, [正文段]) 展开成 chunk 列表。

    doc_id 用标题的 sha1 前 16 位——与政务语料的命名方式一致（那边是 doc_id
    由语料处理脚本生成），char_offset 按段累加，模拟真实切分。
    """
    out: list[dict] = []
    for title, source, date, texts in rows:
        doc_id = hashlib.sha1(title.encode("utf-8")).hexdigest()[:16]
        offset = 0
        for i, text in enumerate(texts):
            out.append({
                "chunk_id": f"{doc_id}-{i:04d}",
                "doc_id": doc_id,
                "char_offset": offset,
                "title": title,
                "date": date,
                "source": source,
                "text": text,
            })
            offset += len(text)
    return out


def write_domain(chunks: list[dict], path: str) -> int:
    with gzip.open(path, "wt", encoding="utf-8") as f:
        for c in chunks:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    return os.path.getsize(path)


def main() -> int:
    ap = argparse.ArgumentParser(description="生成多领域测试语料")
    ap.add_argument("--out", default=os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "..", "ict-multidomain"),
        help="输出目录（默认 ../ict-multidomain/）")
    ap.add_argument("--self-test", action="store_true", help="只跑自测")
    a = ap.parse_args()

    if a.self_test:
        ok = total = 0

        def check(name: str, cond: bool, detail: str = "") -> None:
            nonlocal ok, total
            total += 1
            ok += 1 if cond else 0
            print(f"  {'✓' if cond else '✗'} {name}{(' — ' + detail) if detail and not cond else ''}")

        for dom, rows in DOMAINS.items():
            chunks = build_domain(rows, dom)
            check(f"{dom}: 每篇都有 chunk", all(len(r[3]) >= 2 for r in rows),
                  f"{[r[0] for r in rows if len(r[3]) < 2]}")
            check(f"{dom}: chunk_id 唯一", len({c['chunk_id'] for c in chunks}) == len(chunks))
            check(f"{dom}: 字段齐全", all(set(c) == set(FIELDS) for c in chunks))
            check(f"{dom}: char_offset 递增", all(
                c["char_offset"] >= 0 for c in chunks))
        check(f"领域数 ≥ 3（实为 {len(DOMAINS)}）", len(DOMAINS) >= 3)
        # 跨领域正文不重复：同一句不该同时出现在两个领域里
        seen: dict[str, str] = {}
        dup = None
        for dom, rows in DOMAINS.items():
            for _t, _s, _d, texts in rows:
                for t in texts:
                    if t in seen and seen[t] != dom:
                        dup = f"{seen[t]} / {dom}: {t[:24]}"
                    seen.setdefault(t, dom)
        check("跨领域正文不重复", dup is None, f"重复：{dup}")
        print(f"\n[gen-domains] {ok}/{total}")
        return 0 if ok == total else 1

    out_dir = os.path.abspath(a.out)
    os.makedirs(out_dir, exist_ok=True)
    print(f"输出目录：{out_dir}\n")
    for dom, rows in DOMAINS.items():
        chunks = build_domain(rows, dom)
        path = os.path.join(out_dir, f"{dom}.jsonl.gz")
        size = write_domain(chunks, path)
        docs = len({c["doc_id"] for c in chunks})
        chars = sum(len(c["text"]) for c in chunks)
        print(f"  {dom:10s} {len(chunks):3d} 块 / {docs:2d} 篇 / {chars:6d} 字 → {size:6d} B  {path}")
    print("\n验证「换语料不改代码」：")
    print(f"  python3 tests/test_lookup.py            # 用包内政务语料")
    print(f"  ICT_TRACK2_DATA={out_dir}/medical.jsonl.gz python3 tests/test_lookup.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
